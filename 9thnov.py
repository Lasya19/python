class Codegnan:
    def __init__(self,name,email,phone):
        self.name=name
        self.email=email
        self.phone=phone

    def Display(self):
        print(self.name,self.email,self.phone)

class Students(Codegnan):
    def __init__(self,name,email,phone,graduation,course):
        super().__init__(name,email,phone)
        self.graduation=graduation
        self.course=course
    def Display(self):
        super().Display()
        print(self.graduation,self.course)
class Trainers(Students):
    def __init__(self,name,email,phone,graduation,course,subject):
        super().__init__(name,email,phone,graduation,course)
        self.subject=subject

    def Display(self):
        super().Display()
        print(self.subject)
