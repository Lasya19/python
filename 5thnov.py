class ATM():
    Accounts = {}
    def __init__(self, account):
        self.account = account
    def createaccount(self, account):
        self.account = account
        if account not in ATM.Accounts:
            password = int(input(f"What is the password you want to keep for you account {account}: "))
            balance = 0
            ATM.Accounts[account] = [password, balance]
            print("Account created successfully")
        else:
            print("Account already exists")
        print(ATM.Accounts)
    def login(self, account):
        self.account = account
        if account in ATM.Accounts:
            attempts = 1
            pin = int(input("What is your pin: "))
            while pin != ATM.Accounts[account][0] and attempts < 3:
                attempts += 1
                print(f"Wrong pin, attempts left={4-attempts}")
                if attempts < 3:
                    pin = int(input("What is your pin: "))
            else:
                if pin == ATM.Accounts[account][0]:
                    print("Logged in successfully")
                else:
                    print("Attempts over")
        else:
            print("Account does not exist")
            self.createaccount(self.account)
    def changepassword(self, account, password):
        self.account = account
        if account in ATM.Accounts:
            if password == ATM.Accounts[self.account][0]:
                new_password = int(input("Enter your new password: "))
                ATM.Accounts[self.account][0] = new_password
                print("Password changed successfully")
            else:
                print("Incorrect old password")
        else:
            print("Account does not exist")
    def Display(self):
        if self.account in ATM.Accounts:
            print(f"Your account is: {self.account}")
            print(f"Your account balance is: {ATM.Accounts[self.account][1]}")
        else:
            print("Account does not exist create a new account")
            self.createaccount(self.account)
    def Deposit(self, amount):
        if self.account not in ATM.Accounts:
           pin_number = int(input("What is your pin: "))
           attempts = 1
           while attempts < 4:
            if pin_number == ATM.Accounts[self.account][0]:
                if amount > 0 and amount % 100 == 0:
                    ATM.Accounts[self.account][1] += amount
                    print(f"Successfully credited. Balance: {ATM.Accounts[self.account][1]}")
                else:
                    print("Invalid deposit amount")
                break
